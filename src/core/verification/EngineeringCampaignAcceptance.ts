/**
 * Evidence-based acceptance for the THREE DIFFERENT 26-agent claims:
 *  (1) live provider operational on a current host;
 *  (2) a complete, controlled, dependency-aware engineering campaign;
 *  (3) independent engineering evidence for each specialist.
 *
 * A test mock or an LLM saying "verified" is NEVER independent validation.
 * The final vessel release authority is deliberately outside this module.
 */
import { createHash, createPublicKey, verify } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { AgentRegistry } from '../registry/AgentRegistry.ts';
import { ROLE_ACCURACY_OBLIGATIONS } from './RoleAccuracyObligations.ts';
import type { AgentMatrixReport, AgentRunFinding } from './LiveAgentMatrix.ts';
import type { CodexCampaignPreflight } from './CodexCampaignPreflight.ts';

export const EXTERNAL_REVIEW_SCHEMA = 'usv01-external-engineering-review/v1' as const;
export const HOST_HEALTH_SCHEMA = 'usv01-host-commissioning-health/v1' as const;
const SHA = /^sha256:[0-9a-f]{64}$/;
const GIT_SHA = /^[a-f0-9]{40}$/;
const ROLE = /^A(0[1-9]|1[0-9]|2[0-6])$/;

export interface ExternalEngineeringReview {
  schema: typeof EXTERNAL_REVIEW_SCHEMA;
  canonicalId: string;
  implementationSha: string;
  agentOutputSha256: string;
  referencePath: string;
  referenceSha256: string;
  verifierId: string;
  reviewerQualification: string;
  method: string;
  finding: 'ACCEPT' | 'REJECT';
  signedAt: string;
  signatureBase64: string;
}

export interface SignedHostHealth {
  schema: typeof HOST_HEALTH_SCHEMA;
  hostId: string;
  implementationSha: string;
  campaignReportSha256: string;
  observedAt: string;
  runtimeHealthy: boolean;
  codexAuthenticated: boolean;
  registeredAgents: number;
  signatureBase64: string;
}

export interface LiveCampaignEvidence extends AgentMatrixReport {
  implementationSha: string;
  catalogSha256: string;
  dataClassification: string;
  commissioning?: { permitted: boolean; scope: string; engineeringReleaseApproved: false };
  /** Optional current-vessel configuration record for actual engineering input. */
  controlledVesselConfigurationId?: string;
  dependencyAware?: boolean;
}

export interface EvidenceAssessment {
  assessedAt: string;
  implementationSha: string;
  operationalOnCurrentInfrastructure: boolean;
  fullyAutomatedEngineeringCampaign: boolean;
  independentlyValidatedEngineeringOutputs: boolean;
  liveCodexAgents: number;
  independentlyAttestedAgents: number;
  hostHealthVerified: boolean;
  deficiencies: {
    operational: string[];
    campaign: string[];
    independentValidation: string[];
  };
  perAgent: Array<{
    canonicalId: string;
    liveExecuted: boolean;
    independentReviewAttested: boolean;
    blockers: string[];
  }>;
  engineeringReleaseApproved: false;
  vesselDesignCertified: false;
}

/**
 * Deterministic canonical fields for review signatures. The public key
 * must be provisioned independently of the agent/PR (e.g. protected runner
 * secret or reviewer's managed trust store), never generated by an agent.
 */
export function canonicalExternalReview(record: ExternalEngineeringReview): string {
  return JSON.stringify({
    schema: record.schema, canonicalId: record.canonicalId,
    implementationSha: record.implementationSha,
    agentOutputSha256: record.agentOutputSha256,
    referencePath: record.referencePath, referenceSha256: record.referenceSha256,
    verifierId: record.verifierId,
    reviewerQualification: record.reviewerQualification,
    method: record.method, finding: record.finding, signedAt: record.signedAt
  });
}
export function canonicalHostHealth(record: SignedHostHealth): string {
  return JSON.stringify({
    schema: record.schema, hostId: record.hostId,
    implementationSha: record.implementationSha,
    campaignReportSha256: record.campaignReportSha256,
    observedAt: record.observedAt, runtimeHealthy: record.runtimeHealthy,
    codexAuthenticated: record.codexAuthenticated,
    registeredAgents: record.registeredAgents
  });
}

function verifySignature(payload: string, signature: string, keyPem?: string): boolean {
  if (!keyPem || !signature || !/^[A-Za-z0-9+/=]+$/.test(signature)) return false;
  try {
    return verify(null, Buffer.from(payload, 'utf8'),
      createPublicKey(keyPem), Buffer.from(signature, 'base64'));
  } catch { return false; }
}

function ageValid(iso: string, currentMs: number, maxAgeMs: number): boolean {
  const time = Date.parse(iso);
  return Number.isFinite(time) && time <= currentMs + 60_000 &&
    currentMs - time >= -60_000 && currentMs - time <= maxAgeMs;
}

function hashBytes(data: Buffer): string {
  return 'sha256:' + createHash('sha256').update(data).digest('hex');
}

export interface EvidenceAssessmentOptions {
  now?: Date;
  /** Exact pinned Git SHA; never a synthetic merge ref. */
  expectedCommit: string;
  /** SHA-256 of original JSON file bytes bound to the signed host report. */
  campaignReportSha256?: string;
  host?: SignedHostHealth;
  hostPublicKeyPem?: string;
  reviews?: ExternalEngineeringReview[];
  independentReviewerPublicKeyPem?: string;
  referenceRootDir?: string;
  preflight?: CodexCampaignPreflight;
}

export function assessEngineeringCampaign(
  report: LiveCampaignEvidence | undefined,
  options: EvidenceAssessmentOptions
): EvidenceAssessment {
  const now = options.now?.getTime() ?? Date.now();
  const operational: string[] = [];
  const campaign: string[] = [];
  const independentValidation: string[] = [];
  const byId = new Map<string, AgentRunFinding>();
  const required = AgentRegistry.getInstance().getAllAgents();
  const canonicalIds = required.map(x => x.canonicalId);
  const missingReferenceRows: string[] = [];

  if (!GIT_SHA.test(options.expectedCommit)) {
    operational.push('Exact 40-hex implementation SHA not provided');
  }
  if (!report) {
    operational.push('Authenticated 26-agent live campaign report is missing');
    campaign.push('Controlled live engineering campaign report is missing');
    independentValidation.push('No independently reviewed outputs can be tied to a live campaign');
  } else {
    if (report.implementationSha !== options.expectedCommit) {
      operational.push('Live campaign implementation SHA differs from exact source commit');
    }
    if (!SHA.test(report.catalogSha256)) {
      campaign.push('Source input catalog SHA-256 is missing or invalid');
    }
    if (report.totalAgents !== 26 || report.findings.length !== 26 ||
        new Set(report.findings.map(x => x.canonicalId)).size !== 26) {
      operational.push('Report must contain exactly 26 unique canonical agent outcomes');
    }
    for (const item of report.findings) byId.set(item.canonicalId, item);
    if (!report.providerOperationalMatrixComplete || report.liveProviderRuns !== 26) {
      operational.push('26/26 real provider executions were not confirmed');
    }
    if (report.commissioning?.permitted !== true ||
        report.commissioning?.scope !== 'LAB_COMMISSIONING_RESEARCH' ||
        report.commissioning?.engineeringReleaseApproved !== false) {
      operational.push('Restricted non-operational lab commissioning authority was not evidenced');
    }
    if (report.dataClassification !== 'CONTROLLED_ENGINEERING_EVIDENCE' ||
        !report.controlledVesselConfigurationId?.trim()) {
      campaign.push('Actual controlled vessel configuration and inputs are missing; synthetic commissioning cases are not an engineering campaign');
    }
    if (report.dependencyAware !== true) {
      campaign.push('Agent dependencies and real inter-specialist handoffs were not enforced');
    }
    if (!options.preflight ||
        options.preflight.status !== 'PREFLIGHT_READY_NO_AI_CALLS' ||
        options.preflight.totalAgents !== 26 ||
        options.preflight.deterministicToolsFailed !== 0 ||
        options.preflight.deterministicToolsExpectedRejections !== 0) {
      campaign.push('Complete 26-role deterministic-tool preflight with no unresolved input or tool rejections is missing');
    }
    if (report.engineeringReleaseApproved !== false ||
        report.independentlyEngineeringValidated !== false) {
      campaign.push('Campaign attempted to claim an unauthorized engineering release or self-validation');
    }
  }

  // A historic model report does not show that an execution service is
  // working NOW. Require a fresh host-signed health and Codex login attestation.
  let hostHealthVerified = false;
  const host = options.host;
  if (!host) {
    operational.push('No current signed host health/CLI-authentication evidence');
  } else if (host.schema !== HOST_HEALTH_SCHEMA ||
      !host.hostId?.trim() ||
      host.implementationSha !== options.expectedCommit ||
      !options.campaignReportSha256 ||
      host.campaignReportSha256 !== options.campaignReportSha256 ||
      !host.runtimeHealthy || !host.codexAuthenticated ||
      host.registeredAgents !== 26 ||
      !ageValid(host.observedAt, now, 5 * 60_000) ||
      !verifySignature(canonicalHostHealth(host), host.signatureBase64, options.hostPublicKeyPem)) {
    operational.push('Host health evidence is stale, unsigned, untrusted, incorrect, or not bound to this campaign');
  } else {
    hostHealthVerified = true;
  }

  const reviews = options.reviews ?? [];
  const observedReviews = new Set<string>();
  const perAgent = required.map(spec => {
    const issues: string[] = [];
    const run = byId.get(spec.canonicalId);
    const liveExecuted = !!run &&
      run.runtimeId === spec.id &&
      run.status === 'LIVE_PROVIDER_EXECUTED_UNCERTIFIED' &&
      run.provider === 'codex_cli' &&
      run.providerExecutionMode === 'LIVE_AI_GENERATION' &&
      run.requiredToolsVerified === true &&
      !!run.correlationId &&
      !!run.inputTaskId &&
      SHA.test(run.outputDigestSha256 || '') &&
      !!run.completedAt && ageValid(run.completedAt, now, 31 * 24 * 60 * 60_000);
    if (!liveExecuted) issues.push('Missing complete authenticated Codex role trace and deterministic-tool evidence');
    const matches = reviews.filter(r => r.canonicalId === spec.canonicalId);
    if (matches.length !== 1) issues.push('Exactly one independently signed review is required per role');
    const review = matches[0];
    let independentReviewAttested = false;
    if (liveExecuted && matches.length === 1 && review) {
      const relativePath = typeof review.referencePath === 'string' ? review.referencePath : '';
      const root = options.referenceRootDir ? path.resolve(options.referenceRootDir) : '';
      const artifactPath = root ? path.resolve(root, relativePath) : '';
      const localEvidence = !!root &&
        relativePath.startsWith('evidence/independent/') &&
        artifactPath.startsWith(root + path.sep) &&
        fs.existsSync(artifactPath) && fs.statSync(artifactPath).isFile() &&
        fs.statSync(artifactPath).size <= 5 * 1024 * 1024;
      const artifactMatches = localEvidence &&
        hashBytes(fs.readFileSync(artifactPath)) === review.referenceSha256;
      independentReviewAttested = review.schema === EXTERNAL_REVIEW_SCHEMA &&
        ROLE.test(review.canonicalId) &&
        review.implementationSha === options.expectedCommit &&
        review.agentOutputSha256 === run!.outputDigestSha256 &&
        review.finding === 'ACCEPT' &&
        !!review.verifierId?.trim() &&
        review.verifierId !== spec.id &&
        !!review.reviewerQualification?.trim() &&
        !!review.method?.trim() &&
        ageValid(review.signedAt, now, 180 * 24 * 60 * 60_000) &&
        !!artifactMatches &&
        verifySignature(canonicalExternalReview(review), review.signatureBase64,
          options.independentReviewerPublicKeyPem);
      if (!independentReviewAttested) {
        issues.push('External reviewer attestation or independently sourced reference is missing, invalid, or does not match the exact live output');
      }
    }
    if (!independentReviewAttested) missingReferenceRows.push(spec.canonicalId);
    if (independentReviewAttested) observedReviews.add(spec.canonicalId);
    return { canonicalId: spec.canonicalId, liveExecuted, independentReviewAttested, blockers: issues };
  });
  if (reviews.some(r => !canonicalIds.includes(r.canonicalId))) {
    independentValidation.push('Review pack contains unknown specialist identifiers');
  }
  if (missingReferenceRows.length) {
    independentValidation.push('Signed external evidence missing/invalid for: ' + missingReferenceRows.join(', '));
  }

  const liveCodexAgents = perAgent.filter(x => x.liveExecuted).length;
  if (liveCodexAgents !== 26) operational.push('Role-specific live traces are incomplete: ' + liveCodexAgents + '/26');
  if (liveCodexAgents !== 26) campaign.push('The end-to-end campaign lacks 26 accepted live specialist outcomes');
  if (!hostHealthVerified) campaign.push('Current execution host is not independently health-attested');
  const fullyAutomatedEngineeringCampaign = operational.length === 0 && campaign.length === 0;
  const independentlyValidatedEngineeringOutputs =
    fullyAutomatedEngineeringCampaign && independentValidation.length === 0 && observedReviews.size === 26;

  return {
    assessedAt: new Date(now).toISOString(),
    implementationSha: options.expectedCommit,
    operationalOnCurrentInfrastructure: operational.length === 0 && liveCodexAgents === 26,
    fullyAutomatedEngineeringCampaign,
    independentlyValidatedEngineeringOutputs,
    liveCodexAgents,
    independentlyAttestedAgents: observedReviews.size,
    hostHealthVerified,
    deficiencies: { operational, campaign, independentValidation },
    perAgent,
    engineeringReleaseApproved: false,
    vesselDesignCertified: false
  };
}
